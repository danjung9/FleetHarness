import { chromium, _electron as electron } from 'playwright';
import { preview } from 'vite';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { startFixtureProvider } from './mock-provider.mjs';

const root = await fs.mkdtemp(path.join(os.tmpdir(), 'fleet-studio-check-'));
const output = path.resolve('output/playwright/studio');
await fs.mkdir(output, { recursive: true });
const server = await preview({ configFile: 'vite.studio.config.ts', preview: { host: '127.0.0.1', port: 0, strictPort: false } });
const address = server.httpServer.address();
const url = `http://127.0.0.1:${address.port}/studio/index.html`;
const errors = [];
async function capture(page, name) {
  await page.evaluate(() => document.fonts.ready);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.screenshot({ path: path.join(output, name), fullPage: true, animations: 'disabled', scale: 'css' });
}
let browser, desktop, fixture;
try {
  browser = await chromium.launch({ headless: true, channel: process.env.FLEET_BROWSER_CHANNEL || 'chrome', args: ['--disable-gpu'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(url);
  await page.getByRole('heading', { name: 'Hard problems. Working software.' }).waitFor();
  await page.evaluate(() => document.fonts.ready);
  await capture(page, 'desktop.png');
  await page.setViewportSize({ width: 390, height: 844 });
  await capture(page, 'mobile.png');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile directory must not overflow');
  await page.getByRole('button', { name: 'Knowledge & search', exact: true }).click();
  assert.ok(await page.locator('.challenge-card').count() > 0);
  assert.match(await page.locator('.results-bar').innerText(), /Knowledge & search/);
  await page.getByRole('button', { name: 'All challenges', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.keyboard.press('/');
  assert.equal(await page.getByLabel('Search challenges').evaluate(el => document.activeElement === el), true);
  await page.getByLabel('Search challenges').fill('OPTASK');
  assert.equal(await page.locator('.challenge-card').count(), 1);
  await page.locator('.save-button').click();
  await page.getByRole('button', { name: 'Clear search' }).click();
  await page.getByRole('button', { name: 'Saved 1', exact: true }).click();
  assert.equal(await page.locator('.challenge-card').count(), 1);
  await page.locator('.card-body').click();
  await page.getByRole('heading', { name: /Electronic OPTASK/ }).waitFor();
  await capture(page, 'detail-desktop.png');
  await page.setViewportSize({ width: 390, height: 844 });
  await capture(page, 'detail-mobile.png');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Build this challenge' }).click();
  const briefRoute = page.url();
  await page.getByRole('link', { name: 'Skip to content' }).focus();
  await page.keyboard.press('Enter');
  assert.equal(page.url(), briefRoute, 'Skip link must preserve editor route');
  assert.equal(await page.locator('main').evaluate(el => el === document.activeElement), true);
  assert.match(await page.getByLabel('Challenge title', { exact: true }).inputValue(), /OPTASK/);
  await page.getByLabel('Expected deliverable', { exact: true }).fill('A self-contained timeline application with meaningful Node tests and documentation.');
  await page.getByLabel('Resources', { exact: true }).fill('Synthetic input messages and a human-reviewed answer key.');
  await page.getByLabel('Links', { exact: true }).fill('https://cdao.hackathon.maximus.com/event/norfolk/use-cases/12');
  await page.getByText('Draft saved on this device').waitFor();
  await page.reload();
  assert.match(await page.getByLabel('Challenge title', { exact: true }).inputValue(), /OPTASK/);
  assert.equal(await page.getByLabel('Resources', { exact: true }).inputValue(), 'Synthetic input messages and a human-reviewed answer key.');
  await capture(page, 'editor-mobile.png');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await capture(page, 'editor-desktop.png');
  assert.equal(await page.getByRole('button', { name: 'Generate software', exact: true }).isDisabled(), true, 'Browser must not claim live generation');
  await page.getByRole('button', { name: 'Save brief', exact: true }).click();
  await page.getByRole('status').waitFor();
  await page.getByRole('button', { name: 'Edit brief', exact: true }).click();
  const editedTitle = 'Revised OPTASK build';
  await page.getByLabel('Challenge title', { exact: true }).fill(editedTitle);
  await page.getByLabel('Overview', { exact: true }).fill('Interpret synthetic messages and retain literal headings such as ## Resources inside the user overview.');
  await page.getByRole('button', { name: 'Save brief', exact: true }).click();
  await page.reload();
  await page.getByRole('heading', { name: editedTitle, exact: true }).waitFor();
  const browserState = await page.evaluate(() => JSON.parse(localStorage.getItem('fleetharness-studio-preview-v1')));
  assert.equal(browserState.projects.length, 1, 'Editing should update, not duplicate');
  assert.equal(browserState.projects[0].challengeId, '12');
  assert.match(browserState.projects[0].description, /## Expected deliverable/);
  assert.match(browserState.projects[0].description, /Synthetic input messages and a human-reviewed answer key/);
  assert.equal(await page.evaluate(() => localStorage.getItem('fleet-browser-preview')), null, 'Original browser storage stays untouched');
  await page.getByRole('button', { name: 'Edit brief', exact: true }).click();
  assert.match(await page.getByLabel('Overview', { exact: true }).inputValue(), /## Resources/);
  const brief = await page.evaluate(() => {
    const saved = JSON.parse(localStorage.getItem('fleetharness-studio-preview-v1')).projects[0];
    return JSON.parse(saved.description.split('\n\n<!-- fleetharness-studio-brief:v1 -->\n')[1]);
  });
  await fs.writeFile(path.join(root, 'brief.json'), JSON.stringify(brief));
  await browser.close(); browser = undefined;

  fixture = await startFixtureProvider();
  const piDir = path.join(root, 'pi'); await fs.mkdir(piDir);
  await fs.writeFile(path.join(piDir, 'models.json'), JSON.stringify({ providers: { 'fleet-fixture': { baseUrl: fixture.baseUrl, api: 'openai-completions', apiKey: 'local-fixture-only', models: [{ id: 'fixture-model', name: 'Local test fixture', reasoning: false, input: ['text'], contextWindow: 64000, maxTokens: 8000, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 } }] } } }));
  desktop = await electron.launch({ args: ['.'], env: { ...process.env, FLEET_USER_DATA: path.join(root, 'studio-state'), PI_CODING_AGENT_DIR: piDir, VITE_DEV_SERVER_URL: url }, timeout: 45000 });
  const app = await desktop.firstWindow();
  app.on('pageerror', e => errors.push(e.message));
  await app.getByRole('heading', { name: 'Hard problems. Working software.' }).waitFor({ timeout: 45000 });
  await app.getByRole('button', { name: 'Connect Pi', exact: true }).click();

  await app.getByLabel('Provider', { exact: true }).selectOption('fleet-fixture');
  await app.getByRole('button', { name: 'Save Pi settings' }).click();
  await app.getByText('Pi settings saved.', { exact: true }).waitFor();
  await app.getByLabel('Choose brief JSON').setInputFiles(path.join(root, 'brief.json'));
  await app.getByText('Brief imported. Open My builds to edit or generate it.').waitFor();
  await app.getByRole('button', { name: /My builds/ }).click();
  await app.getByRole('heading', { name: editedTitle, exact: true }).click();
  await app.getByRole('button', { name: 'Generate software', exact: true }).click();
  await app.getByText('Ready for review', { exact: true }).waitFor({ timeout: 90000 });
  const built = await app.evaluate(async () => (await window.fleetHarness.bootstrap()).state.projects.find(p => p.title === 'Revised OPTASK build'));
  assert.equal(built.status, 'review', built.error);
  assert.equal(built.report.passed, 1);
  assert.ok(built.logs.some(l => l.text.includes('Starting one Pi repair attempt')));
  const packet = JSON.parse(await fs.readFile(path.join(built.workspace, '.fleet', 'packet.json'), 'utf8'));
  assert.equal(packet.challenge.id, '12');
  assert.ok(packet.recipe.skills.includes('fleet-messages'));
  assert.ok(packet.recipe.tools.includes('fleet_extract_messages'));
  assert.match(packet.userScope.description, /## Requirements/);
  assert.match(packet.userScope.description, /## Expected deliverable/);
  assert.match(packet.userScope.description, /## Resources/);
  assert.match(packet.userScope.description, /## Links/);
  assert.ok(packet.userScope.criteria.length > 0);
  const activityTab = app.getByRole('tab', { name: 'Agent activity', exact: true });
  await activityTab.focus();
  await app.keyboard.press('End');
  assert.equal(await app.getByRole('tab', { name: 'Review & delivery' }).getAttribute('aria-selected'), 'true');
  await app.keyboard.press('Home');
  assert.equal(await activityTab.getAttribute('aria-selected'), 'true');
  await app.keyboard.press('ArrowLeft');
  assert.equal(await app.getByRole('tab', { name: 'Review & delivery' }).getAttribute('aria-selected'), 'true');
  await app.keyboard.press('ArrowRight');
  await app.keyboard.press('ArrowRight');
  assert.equal(await app.getByRole('tab', { name: 'App preview' }).getAttribute('aria-selected'), 'true');
  assert.equal(await app.locator('[role=tab][tabindex="0"]').count(), 1);
  await app.keyboard.press('Tab');
  assert.equal(await app.locator('#build-panel').evaluate(el => document.activeElement === el), true);
  await app.frameLocator('iframe').getByRole('button', { name: 'Parse message' }).click();
  assert.match(await app.frameLocator('iframe').locator('#result').textContent(), /inspect pump/);
  await app.screenshot({ path: path.join(output, 'build-desktop.png'), animations: 'disabled' });
  await app.getByRole('tab', { name: 'Review & delivery', exact: true }).click();
  await app.getByLabel('Review notes').fill('Inspected this local fixture preview and independent test results. Integration test only.');
  await app.getByLabel('I inspected the application, evidence, and limitations.').check();
  await app.getByRole('button', { name: 'Approve prototype' }).click();
  await app.getByText('Approved for prototype delivery').waitFor();
  const deliveryDir = path.join(root, 'delivery'); await fs.mkdir(deliveryDir);
  await desktop.evaluate(({ dialog }, dir) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [dir] }); }, deliveryDir);
  await app.getByRole('button', { name: 'Export app & evidence' }).click();
  await app.getByText('Delivered', { exact: true }).waitFor();
  const delivered = await app.evaluate(async id => (await window.fleetHarness.bootstrap()).state.projects.find(p => p.id === id), built.id);
  assert.ok((await fs.readFile(path.join(delivered.exportedTo, 'DELIVERY.md'), 'utf8')).includes('1/1 passed'));
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, browser: ['search', 'bookmark', 'responsive directory/detail/editor', 'draft restoration', 'create/edit persistence', 'original storage isolated', 'browser run unavailable'], desktop: ['import', 'Pi model settings', 'existing Pi backend', 'six intake sections preserved', 'domain skills and tools', 'real fixture generation', 'independent tests', 'repair loop', 'working preview', 'human review', 'export'], rendererErrors: errors, screenshots: output }, null, 2));
} finally {
  await browser?.close(); await desktop?.close(); await fixture?.close();
  await new Promise(resolve => server.httpServer.close(resolve));
  await fs.rm(root, { recursive: true, force: true });
}
