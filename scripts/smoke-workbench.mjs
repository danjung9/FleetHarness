import { chromium, _electron as electron } from 'playwright';
import { preview } from 'vite';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { startFixtureProvider } from './mock-provider.mjs';

const root = await fs.mkdtemp(path.join(os.tmpdir(), 'fleet-workbench-check-'));
const output = path.resolve('output/playwright/workbench');
await fs.mkdir(output, { recursive: true });
const server = await preview({ configFile: 'vite.workbench.config.ts', preview: { host: '127.0.0.1', port: 0, strictPort: false } });
const url = `http://127.0.0.1:${server.httpServer.address().port}/workbench/index.html`;
const errors = [];
let browser, desktop, fixture;
async function capture(page, name) {
  await page.evaluate(() => document.fonts.ready);
  const dismiss = page.getByRole('button', { name: 'Dismiss notification', exact: true });
  if (await dismiss.count()) await dismiss.click();
  await page.evaluate(() => { window.scrollTo(0, 0); document.getElementById('wb-main').scrollTop = 0; });
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.screenshot({ path: path.join(output, name + '.png'), fullPage: true, animations: 'disabled', scale: 'css' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, name + ' must not overflow horizontally');
}
try {
  browser = await chromium.launch({ headless: true, channel: process.env.FLEET_BROWSER_CHANNEL || 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(new URL('/', url).href);
  assert.equal(new URL(page.url()).pathname, '/workbench/index.html', 'Workbench root must open version 3');
  await page.getByRole('heading', { name: 'What do you need to get done?' }).waitFor();
  assert.equal(await page.locator('.wb-challenge-row').count(), 34);
  await capture(page, 'desktop');
  await page.setViewportSize({ width: 1120, height: 720 });
  await capture(page, 'minimum');
  await page.setViewportSize({ width: 900, height: 800 });
  assert.equal(await page.getByRole('link', { name: 'FleetHarness — Find a solution', exact: true }).count(), 1);
  for (const name of ['Find a solution (34)', 'My tools (0)', 'Needs my review (0)']) assert.equal(await page.getByRole('link', { name, exact: true }).count(), 1);
  const secondChallenge = page.locator('.wb-challenge-row').nth(1);
  await secondChallenge.focus(); await page.keyboard.press('Enter');
  await page.getByRole('heading', { name: 'Make a training plan without clashes', exact: true }).waitFor();
  assert.equal(await secondChallenge.evaluate(el => el === document.activeElement), true, 'Desktop challenge selection must retain keyboard focus');
  await capture(page, 'compact');
  await page.getByRole('link', { name: 'FleetHarness — Find a solution', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await capture(page, 'mobile');
  await page.getByRole('button', { name: 'Starter challenges', exact: true }).click();
  assert.equal(await page.locator('.wb-challenge-row').count(), 3);
  await page.getByRole('button', { name: 'Starter challenges', exact: true }).click();
  await page.getByLabel('Filter by domain').selectOption('cyber');
  assert.ok(await page.locator('.wb-challenge-row').count() > 0);
  await page.getByLabel('Filter by domain').selectOption('all');
  await page.getByLabel('Search challenges').fill('zz-no-matches');
  await page.getByRole('heading', { name: 'No matching challenges' }).waitFor();
  await page.getByRole('button', { name: 'Reset filters' }).click();
  await page.locator('.wb-challenge-row').first().click();
  await page.getByRole('link', { name: 'Make this my problem' }).waitFor();
  await capture(page, 'detail-mobile');
  await page.getByRole('button', { name: 'All challenges', exact: true }).click();
  await page.locator('.wb-challenge-row').first().waitFor({ state: 'visible' });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.keyboard.press('/');
  assert.equal(await page.getByLabel('Search challenges').evaluate(el => el === document.activeElement), true);
  await page.getByLabel('Search challenges').fill('OPTASK');
  assert.equal(await page.locator('.wb-challenge-row').count(), 1);
  await page.getByRole('link', { name: 'Make this my problem' }).click();
  await page.getByLabel('Give your tool a name').fill('My message timeline');
  await page.getByLabel('What’s the problem?').fill('Turn synthetic operational messages into a timeline, keeping source references so that I can check every task.');
  await page.getByLabel('How will you know it works?').fill('Extract tasks from the sample message.\nKeep the original source text.\nHandle an empty message.');
  await page.getByText('Draft saved on this device', { exact: true }).waitFor();
  await capture(page, 'request-desktop');
  await page.setViewportSize({ width: 390, height: 844 });
  await capture(page, 'request-mobile');
  await page.reload();
  assert.equal(await page.getByLabel('Give your tool a name').inputValue(), 'My message timeline');
  const route = page.url();
  await page.getByRole('link', { name: 'Skip to content' }).focus();
  await page.keyboard.press('Enter');
  assert.equal(page.url(), route);
  await page.getByRole('button', { name: 'Save request', exact: true }).click();
  await page.getByRole('heading', { name: 'My message timeline', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Set up connection', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Edit request' }).click();
  await page.getByLabel('Give your tool a name').fill('Updated message timeline');
  await page.getByRole('button', { name: 'Save request', exact: true }).click();
  await page.reload();
  await page.getByRole('heading', { name: 'Updated message timeline', exact: true }).waitFor();
  const state = await page.evaluate(() => JSON.parse(localStorage.getItem('fleetharness-workbench-v1')));
  assert.equal(state.projects.length, 1);
  assert.equal(state.projects[0].challengeId, '12');
  assert.equal(await page.evaluate(() => localStorage.getItem('fleet-browser-preview')), null);
  assert.equal(await page.evaluate(() => localStorage.getItem('fleetharness-studio-preview-v1')), null);
  await capture(page, 'tool-mobile');
  await page.setViewportSize({ width: 1440, height: 960 });
  await capture(page, 'tool-desktop');
  await page.getByRole('tab', { name: 'Your request', exact: true }).focus();
  await page.keyboard.press('End');
  assert.equal(await page.getByRole('tab', { name: 'Technical details' }).getAttribute('aria-selected'), 'true');
  await page.keyboard.press('Home');
  assert.equal(await page.getByRole('tab', { name: 'Your request', exact: true }).getAttribute('aria-selected'), 'true');
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('tab', { name: 'Try your tool' }).getAttribute('aria-selected'), 'true');
  await page.getByRole('tab', { name: 'Review & download' }).click();
  assert.equal(await page.getByRole('button', { name: 'Approve for download' }).isDisabled(), true);
  await page.getByRole('link', { name: /My tools/ }).click();
  await page.getByLabel('Filter build status').selectOption('review');
  await page.getByRole('heading', { name: 'No tools match these filters' }).waitFor();
  const { title, description, criteria, challengeId } = state.projects[0];
  await fs.writeFile(path.join(root, 'request.json'), JSON.stringify({ title, description, criteria, challengeId }));
  await browser.close(); browser = undefined;

  fixture = await startFixtureProvider();
  const piDir = path.join(root, 'pi'); await fs.mkdir(piDir);
  await fs.writeFile(path.join(piDir, 'models.json'), JSON.stringify({ providers: { 'fleet-fixture': { baseUrl: fixture.baseUrl, api: 'openai-completions', apiKey: 'local-fixture-only', models: [{ id: 'fixture-model', name: 'Local test fixture', reasoning: false, input: ['text'], contextWindow: 64000, maxTokens: 8000, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 } }] } } }));
  desktop = await electron.launch({ args: ['.'], env: { ...process.env, FLEET_USER_DATA: path.join(root, 'workbench-state'), PI_CODING_AGENT_DIR: piDir, VITE_DEV_SERVER_URL: url }, timeout: 45000 });
  const app = await desktop.firstWindow();
  app.on('pageerror', e => errors.push(e.message));
  await app.getByRole('heading', { name: 'What do you need to get done?' }).waitFor({ timeout: 45000 });
  await app.getByRole('button', { name: 'Set up connection', exact: true }).click();
  await app.getByLabel('Build engine', { exact: true }).selectOption('pi');
  await app.getByLabel('Provider', { exact: true }).selectOption('fleet-fixture');
  await app.getByRole('button', { name: 'Save model settings' }).click();
  await app.getByText('Model settings saved.', { exact: true }).waitFor();
  await app.getByLabel('Choose request file').setInputFiles(path.join(root, 'request.json'));
  await app.getByRole('heading', { name: title, exact: true }).waitFor();
  await app.getByRole('button', { name: 'Create my tool', exact: true }).click();
  await app.locator('.wb-build-heading .wb-status.review, .wb-build-heading .wb-status.failed').waitFor({ timeout: 90000 });
  const built = await app.evaluate(async () => (await window.fleetHarness.bootstrap()).state.projects.find(p => p.title === 'Updated message timeline'));
  assert.equal(built.status, 'review', built.error);
  assert.equal(built.report.passed, 1);
  assert.ok(built.logs.some(l => l.text.includes('Starting one Pi repair attempt')));
  const packet = JSON.parse(await fs.readFile(path.join(built.workspace, '.fleet', 'packet.json'), 'utf8'));
  assert.equal(packet.challenge.id, '12');
  assert.ok(packet.recipe.tools.includes('fleet_extract_messages'));
  await app.getByRole('tab', { name: 'Try your tool', exact: true }).click();
  await app.frameLocator('iframe').getByRole('button', { name: 'Parse message' }).click();
  assert.match(await app.frameLocator('iframe').locator('#result').textContent(), /inspect pump/);
  await capture(app, 'preview-desktop');
  await app.getByRole('tab', { name: 'Technical details' }).click();
  await app.getByRole('button', { name: 'Files', exact: true }).click();
  await app.getByRole('button', { name: 'index.html', exact: true }).click();
  await app.locator('.wb-file-view pre').filter({ hasText: '<!doctype html>' }).waitFor();
  await app.getByRole('button', { name: 'System design', exact: true }).click();
  await app.getByRole('heading', { name: 'System design', exact: true }).waitFor();
  await app.getByRole('tab', { name: 'Review & download' }).click();
  await app.getByLabel('What did you check?').fill('Tried the synthetic message and checked the source text and independent test results. Local fixture only.');
  assert.equal(await app.getByRole('button', { name: 'Approve for download' }).isDisabled(), true);
  await app.getByLabel('I tried this tool and reviewed its requirements, checks, and limitations.').check();
  await capture(app, 'review-desktop');
  await app.getByRole('button', { name: 'Approve for download' }).click();
  await app.getByRole('heading', { name: 'Approved for prototype use' }).waitFor();
  const deliveryDir = path.join(root, 'delivery'); await fs.mkdir(deliveryDir);
  await desktop.evaluate(({ dialog }, dir) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [dir] }); }, deliveryDir);
  await app.getByRole('button', { name: 'Export source & evidence', exact: true }).click();
  await app.getByRole('heading', { name: 'Your tool has been downloaded.', exact: true }).waitFor();
  const delivered = await app.evaluate(async id => (await window.fleetHarness.bootstrap()).state.projects.find(p => p.id === id), built.id);
  assert.match(await fs.readFile(path.join(delivered.exportedTo, 'DELIVERY.md'), 'utf8'), /1\/1 passed/);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, browser: ['34 challenges', 'search and domain filters', 'mobile drill-in and back', 'draft restoration', 'request create/edit', 'isolated storage', 'keyboard tabs', 'approval disabled without evidence'], desktop: ['import request', 'connect Pi', 'creation with repair', 'independent verification', 'working preview', 'source files', 'system design', 'human review gate', 'export'], screenshots: output, rendererErrors: errors }, null, 2));
} finally {
  await browser?.close(); await desktop?.close(); await fixture?.close();
  await new Promise(resolve => server.httpServer.close(resolve));
  await fs.rm(root, { recursive: true, force: true });
}
