import { _electron as electron } from 'playwright';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { startFixtureProvider } from './mock-provider.mjs';

const root=await fs.mkdtemp(path.join(os.tmpdir(),'fleet-electron-'));
const piDir=path.join(root,'pi');await fs.mkdir(piDir);
const output=path.resolve('output/playwright');await fs.mkdir(output,{recursive:true});
const fixture=await startFixtureProvider();
await fs.writeFile(path.join(piDir,'models.json'),JSON.stringify({providers:{'fleet-fixture':{baseUrl:fixture.baseUrl,api:'openai-completions',apiKey:'local-fixture-only',models:[{id:'fixture-model',name:'Local test fixture',reasoning:false,input:['text'],contextWindow:64000,maxTokens:8000,cost:{input:0,output:0,cacheRead:0,cacheWrite:0}}]}}}));
const executablePath=process.env.FLEET_EXECUTABLE;
let app;
try {
  app=await electron.launch({ ...(executablePath?{executablePath,args:[]}:{args:['.']}), env:{...process.env,FLEET_USER_DATA:path.join(root,'state'),PI_CODING_AGENT_DIR:piDir},timeout:45000});
  const page=await app.firstWindow();await page.locator('.app-shell').waitFor({timeout:45000});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  assert.equal(await page.evaluate(()=>typeof window.fleetHarness?.startRun),'function');
  assert.equal(await page.evaluate(()=>typeof window.require),'undefined');
  const firstId=await page.evaluate(async()=> (await window.fleetHarness.bootstrap()).state.projects[0].id);
  await assert.rejects(page.evaluate(id=>window.fleetHarness.startRun(id),firstId),/Choose a model/);
  await page.screenshot({path:path.join(output,'factory-desktop.png'),scale:'css'});
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1120,720));
  await page.screenshot({path:path.join(output,'factory-minimum.png'),scale:'css'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1512,982));
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('radio',{name:'Pi Model providers'}).check();
  await page.getByLabel('Provider',{exact:true}).selectOption('fleet-fixture');
  await page.getByRole('button',{name:'Save model settings'}).click();
  await page.getByText('Model settings saved.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'New challenge',exact:true}).click();
  await page.getByRole('button',{name:'Norfolk catalog · 34'}).click();
  await page.getByPlaceholder('Search title, category, or challenge ID').fill('OPTASK');
  await page.locator('.catalog-results button').click();
  assert.match(await page.getByLabel('Challenge title',{exact:true}).inputValue(),/OPTASK/);
  await page.getByRole('button',{name:'Save challenge',exact:true}).click();
  await page.getByText('Challenge saved.',{exact:true}).waitFor();
  const id=await page.evaluate(async()=> (await window.fleetHarness.bootstrap()).state.projects[0].id);
  const saved=await page.evaluate(async()=> (await window.fleetHarness.bootstrap()).state.projects[0]);
  assert.equal(saved.challengeId,'12');
  await page.getByRole('button',{name:'Start build',exact:true}).click();
  await page.getByRole('dialog',{name:'Start build',exact:true}).getByRole('button',{name:'Start automatic build',exact:true}).click();
  await page.waitForFunction(async id => ['review', 'failed', 'stopped'].includes((await window.fleetHarness.bootstrap()).state.projects.find(project => project.id === id)?.status), id, {timeout:90000});
  const final=await page.evaluate(async id=>(await window.fleetHarness.bootstrap()).state.projects.find(p=>p.id===id),id);
  await fs.writeFile(path.join(output,'fixture-run.json'),JSON.stringify(final,null,2));
  assert.equal(final.status,'review',final.error);
  assert.equal(final.report.passed,1);
  assert.ok(final.logs.some(l=>l.text.includes('Starting one Pi repair attempt')));
  assert.ok(final.logs.some(l=>l.kind==='tool'&&l.text.includes('write')));
  await page.getByRole('button',{name:'Preview — generated app',exact:true}).click();
  await page.getByRole('button',{name:'Reload preview'}).click();
  const frame=page.frameLocator('iframe[title="Generated application preview"]');
  await frame.getByRole('button',{name:'Parse message'}).click();
  assert.match(await frame.locator('#result').textContent(),/inspect pump/);
  const child=page.frames().find(f=>f.url().startsWith('http://127.0.0.1:'));
  assert.equal(await child.evaluate(()=>typeof window.fleetHarness),'undefined');
  assert.equal(await child.evaluate(()=>localStorage.getItem('lastParse')),'saved');
  assert.equal(await child.evaluate(()=>{try {void parent.document.body;return 'accessible';}catch{return 'blocked';}}),'blocked');
  await page.screenshot({path:path.join(output,'development-desktop.png'),scale:'css'});
  await page.getByRole('navigation',{name:'Challenge progress',exact:true}).getByRole('button',{name:'Review',exact:true}).click();
  await page.getByLabel('Review notes').fill('Inspected the fixture preview and test output. This is an integration test only.');
  await page.getByLabel('I inspected the application, test evidence, and limitations.').check();
  await page.getByRole('button',{name:'Approve prototype',exact:true}).click();
  await page.getByText('Prototype approved for delivery.',{exact:true}).waitFor();
  await page.getByRole('heading',{name:'Deliver',exact:true}).waitFor();
  const destination=path.join(root,'delivery');await fs.mkdir(destination);
  await app.evaluate(({dialog},dir)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[dir]});},destination);
  await page.getByRole('button',{name:'Export source & evidence',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Source and evidence saved to'}).waitFor({timeout:10000});
  const delivered=await page.evaluate(async id=>(await window.fleetHarness.bootstrap()).state.projects.find(p=>p.id===id),id);
  assert.ok((await fs.readFile(path.join(delivered.exportedTo,'DELIVERY.md'),'utf8')).includes('1/1 passed'));
  await page.locator('.page').evaluate(el=>{el.scrollTop=0;});
  await page.screenshot({path:path.join(output,'evidence-desktop.png'),scale:'css'});
  await page.reload();await page.locator('.app-shell').waitFor();
  assert.equal(await page.evaluate(async id=>(await window.fleetHarness.bootstrap()).state.projects.find(p=>p.id===id)?.status,id),'delivered');
  await fs.appendFile(path.join(delivered.workspace,'index.html'),'\n<!-- changed -->');
  await assert.rejects(page.evaluate(id=>window.fleetHarness.approve(id,'Try stale approval.'),id),/changed after verification/);
  fixture.setDelay(1500);
  const stopProject=await page.evaluate(()=>window.fleetHarness.createProject({title:'Cancellation check',description:'Verify that a Pi run can be interrupted without losing its workspace.',criteria:['Stopping keeps generated artifacts.']}));
  await page.evaluate(id=>window.fleetHarness.startRun(id),stopProject.id);
  await page.evaluate(id=>window.fleetHarness.stopRun(id),stopProject.id);
  for(let i=0;i<50;i++){const status=await page.evaluate(async id=>(await window.fleetHarness.bootstrap()).state.projects.find(p=>p.id===id)?.status,stopProject.id);if(status==='stopped')break;await new Promise(resolve=>setTimeout(resolve,100));}
  assert.equal(await page.evaluate(async id=>(await window.fleetHarness.bootstrap()).state.projects.find(p=>p.id===id)?.status,stopProject.id),'stopped');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,requests:fixture.requests.length,tests:delivered.report.passed,repairLoop:true,reviewAndExport:true,persistence:true,previewIsolation:true,staleEvidenceBlocked:true,cancellation:true,missingCredentialsBlocked:true,rendererErrors:errors.length,screenshots:output},null,2));
} finally {
  await app?.close();await fixture.close();
  await fs.rm(root,{recursive:true,force:true});
}
